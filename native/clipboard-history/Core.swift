struct ClipError: LocalizedError {
  let message: String
  /// Storage a reset can recover (by moving history aside). A locked Keychain is never one of them.
  var resettable = false
  init(_ message: String, resettable: Bool = false) {
    self.message = message
    self.resettable = resettable
  }
  var errorDescription: String? { message }
}
struct Clip: Codable, Equatable, Identifiable {
  var id: String
  var text: String
  var source: String
  var copied: Date
  var favorite: Bool
  var bytes: Int { text.utf8.count }
  var preview: String {
    String(text.prefix(180)).replacingOccurrences(of: "\n", with: " ↵ ").replacingOccurrences(
      of: "\t", with: " ⇥ ")
  }
}
struct ClipLimits {
  var ordinary = 500, favorites = 100, itemBytes = 1_048_576, totalBytes = 16 * 1_048_576
  var age: TimeInterval = 7 * 86_400
}
enum ClipboardPolicy {
  static let ignored = Set([
    "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType", "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping", "Pasteboard generator type", "com.agilebits.onepassword",
    NSPasteboard.PasteboardType.fileURL.rawValue,
  ])
  static func accepts(types: [String], source: String, foreground: String, excluded: Set<String>)
    -> Bool
  {
    Set(types).isDisjoint(with: ignored) && !excluded.contains(source)
      && !excluded.contains(foreground)
  }
  static func matches(_ clip: Clip, query: String) -> Bool {
    query.isEmpty || clip.text.localizedCaseInsensitiveContains(query)
      || clip.source.localizedCaseInsensitiveContains(query)
  }
}
enum ClipKey {
  /// Automatic retries pass `interactive: false` so they can never raise a Keychain prompt.
  private static func copy(interactive: Bool) -> (status: OSStatus, data: Data?) {
    var query: [String: Any] = [
      kSecClass as String: kSecClassGenericPassword,
      kSecAttrService as String: "com.productivity-os.clipboard-history",
      kSecAttrAccount as String: "history-key",
      kSecReturnData as String: true, kSecMatchLimit as String: kSecMatchLimitOne,
    ]
    if !interactive {
      let context = LAContext()
      context.interactionNotAllowed = true
      query[kSecUseAuthenticationContext as String] = context
    }
    var item: CFTypeRef?
    let status = SecItemCopyMatching(query as CFDictionary, &item)
    return (status, item as? Data)
  }
  static func load(create: Bool, interactive: Bool = true) throws -> SymmetricKey {
    let (status, stored) = copy(interactive: interactive)
    if status == errSecSuccess, let stored, stored.count == 32 {
      return SymmetricKey(data: stored)
    }
    guard status == errSecItemNotFound && create else {
      if status == errSecItemNotFound {
        throw ClipError(
          "The clipboard encryption key is missing, so saved history can't be read. Reset History starts a new one.",
          resettable: true)
      }
      throw ClipError(
        "Clipboard encryption key is unavailable. Unlock your login keychain and reopen Clipboard History. Existing history has not been replaced."
      )
    }
    let key = SymmetricKey(size: .bits256)
    let data = key.withUnsafeBytes { Data($0) }
    let add: [String: Any] = [
      kSecClass as String: kSecClassGenericPassword,
      kSecAttrService as String: "com.productivity-os.clipboard-history",
      kSecAttrAccount as String: "history-key",
      kSecValueData as String: data,
      kSecAttrAccessible as String: kSecAttrAccessibleWhenUnlockedThisDeviceOnly,
    ]
    guard SecItemAdd(add as CFDictionary, nil) == errSecSuccess else {
      throw ClipError("Could not save the clipboard encryption key")
    }
    return key
  }
  /// A reset is only safe when the Keychain answers; a locked Keychain must never discard history.
  static func requireAccess() throws {
    let status = copy(interactive: true).status
    guard status == errSecSuccess || status == errSecItemNotFound else {
      throw ClipError("Unlock your login keychain, then try Reset History again. Existing history has not been changed.")
    }
  }
}

/// Access only through ClipWorker. Text and source labels are encrypted before reaching SQLite.
final class ClipStore {
  let key: SymmetricKey
  let limits: ClipLimits
  private var db: OpaquePointer?
  private(set) var clips: [Clip] = []
  /// Damaged or invalid rows found (and removed) at open; history opens without them.
  private(set) var skipped = 0
  /// Advances on every committed change, so callers can skip work when nothing changed.
  private(set) var generation = 0
  init(url: URL, key: SymmetricKey, limits: ClipLimits = ClipLimits()) throws {
    self.key = key
    self.limits = limits
    let fm = FileManager.default
    try fm.createDirectory(
      at: url.deletingLastPathComponent(), withIntermediateDirectories: true,
      attributes: [.posixPermissions: 0o700])
    for path in [
      url.deletingLastPathComponent(), url, URL(fileURLWithPath: url.path + "-wal"),
      URL(fileURLWithPath: url.path + "-shm"),
    ] {
      if (try? path.resourceValues(forKeys: [.isSymbolicLinkKey]).isSymbolicLink) == true {
        throw ClipError("Clipboard storage cannot be a symbolic link")
      }
    }
    guard
      sqlite3_open_v2(
        url.path, &db, SQLITE_OPEN_CREATE | SQLITE_OPEN_READWRITE | SQLITE_OPEN_FULLMUTEX, nil)
        == SQLITE_OK
    else {
      sqlite3_close(db)
      db = nil
      throw ClipError("Cannot open clipboard history", resettable: true)
    }
    do {
      chmod(url.path, 0o600)
      sqlite3_busy_timeout(db, 1500)
      do {
        try sql(
          "PRAGMA journal_mode=DELETE; PRAGMA secure_delete=ON; CREATE TABLE IF NOT EXISTS clips (id TEXT PRIMARY KEY, payload BLOB NOT NULL); CREATE TABLE IF NOT EXISTS metadata (version INTEGER NOT NULL);"
        )
      } catch { throw ClipError("Cannot open clipboard history", resettable: true) }
      let version = try prepare("SELECT version FROM metadata")
      let result = sqlite3_step(version)
      let supported =
        result == SQLITE_DONE || (result == SQLITE_ROW && sqlite3_column_int(version, 0) == 1)
      sqlite3_finalize(version)
      guard supported else {
        throw ClipError("This clipboard database uses an unsupported version", resettable: true)
      }
      if result == SQLITE_DONE { try sql("INSERT INTO metadata VALUES (1)") }
      let rows = try readRows()
      // Authentication failures with no row that opens mean another key: fail closed, change nothing.
      guard rows.rejected == 0 || rows.opened > 0 else {
        throw ClipError(
          "Clipboard history can't be decrypted with the saved key. Existing history has not been changed.",
          resettable: true)
      }
      clips = rows.clips
      skipped = rows.damaged.count
      // With the key verified, unreadable rows are removed so one bad row never blocks history. Removal,
      // trimming and expiry only delete data; if the disk refuses they are retried later, not fatal.
      if !rows.damaged.isEmpty { try? delete(rowids: rows.damaged) }
      try? trim()
      try? expire()
    } catch {
      sqlite3_close(db)
      db = nil
      throw error
    }
  }
  private func readRows() throws -> (clips: [Clip], damaged: [Int64], opened: Int, rejected: Int) {
    let statement = try prepare("SELECT rowid, payload, id FROM clips")
    defer { sqlite3_finalize(statement) }
    var loaded: [Clip] = [], damaged: [Int64] = [], ids = Set<String>()
    var opened = 0, rejected = 0, total = 0
    while true {
      let step = sqlite3_step(statement)
      if step == SQLITE_DONE { break }
      guard step == SQLITE_ROW else {
        throw ClipError("Could not read clipboard history", resettable: true)
      }
      let rowid = sqlite3_column_int64(statement, 0)
      let bytes = sqlite3_column_blob(statement, 1)
      let count = Int(sqlite3_column_bytes(statement, 1))
      guard let bytes, count > 0, count <= limits.itemBytes * 7 + 8192,
        let sealed = try? AES.GCM.SealedBox(combined: Data(bytes: bytes, count: count))
      else {
        damaged.append(rowid)
        continue
      }
      guard let decoded = try? AES.GCM.open(sealed, using: key) else {
        rejected += 1
        damaged.append(rowid)
        continue
      }
      opened += 1
      guard let clip = try? JSONDecoder().decode(Clip.self, from: decoded), !clip.text.isEmpty,
        clip.bytes <= limits.itemBytes, clip.source.utf8.count <= 4096,
        clip.copied.timeIntervalSince1970.isFinite, clip.id == identifier(clip.text),
        let storedID = sqlite3_column_text(statement, 2), String(cString: storedID) == clip.id,
        ids.insert(clip.id).inserted
      else {
        damaged.append(rowid)
        continue
      }
      total += clip.bytes
      // Far beyond anything this build writes: refuse rather than hold unbounded text in memory.
      guard loaded.count < 4 * (limits.ordinary + limits.favorites), total <= 4 * limits.totalBytes
      else { throw ClipError("Clipboard history exceeds its safety limits", resettable: true) }
      loaded.append(clip)
    }
    return (loaded, damaged, opened, rejected)
  }
  private func delete(rowids: [Int64]) throws {
    try sql("BEGIN IMMEDIATE")
    do {
      let statement = try prepare("DELETE FROM clips WHERE rowid=?")
      var status = SQLITE_DONE
      for rowid in rowids where status == SQLITE_DONE {
        sqlite3_reset(statement)
        sqlite3_bind_int64(statement, 1, rowid)
        status = sqlite3_step(statement)
      }
      sqlite3_finalize(statement)
      guard status == SQLITE_DONE else { throw ClipError("Could not remove damaged clipboard entries") }
      try sql("COMMIT")
    } catch {
      try? sql("ROLLBACK")
      throw error
    }
  }
  /// History written under larger limits keeps its newest ordinary entries and every favorite.
  private func trim() throws {
    var next = clips.sorted { $0.copied > $1.copied }
    var ordinary = next.filter { !$0.favorite }.count
    var total = next.reduce(0) { $0 + $1.bytes }
    while ordinary > limits.ordinary || total > limits.totalBytes,
      let victim = next.lastIndex(where: { !$0.favorite })
    {
      ordinary -= 1
      total -= next[victim].bytes
      next.remove(at: victim)
    }
    if next.count != clips.count { try commit(next) }
  }
  /// Moves unreadable history and its SQLite side files aside so a new store can start. Nothing is deleted.
  static func moveAside(_ url: URL) throws -> URL? {
    let fm = FileManager.default
    let stamp = "\(Int(Date().timeIntervalSince1970))-\(UUID().uuidString.prefix(8))"
    let target = url.deletingLastPathComponent().appendingPathComponent(
      url.deletingPathExtension().lastPathComponent + "-unreadable-\(stamp).sqlite")
    var moved: URL?
    for suffix in ["", "-wal", "-shm", "-journal"] where (try? fm.attributesOfItem(atPath: url.path + suffix)) != nil {
      try fm.moveItem(atPath: url.path + suffix, toPath: target.path + suffix)
      if suffix.isEmpty { moved = target }
    }
    return moved
  }
  deinit { sqlite3_close(db) }
  private func prepare(_ command: String) throws -> OpaquePointer {
    var stmt: OpaquePointer?
    guard sqlite3_prepare_v2(db, command, -1, &stmt, nil) == SQLITE_OK, let stmt else {
      throw ClipError("Clipboard storage operation failed")
    }
    return stmt
  }
  private func sql(_ command: String) throws {
    guard sqlite3_exec(db, command, nil, nil, nil) == SQLITE_OK else {
      throw ClipError("Clipboard storage operation failed. Check available disk space.")
    }
  }
  func identifier(_ text: String) -> String {
    HMAC<SHA256>.authenticationCode(for: Data(text.utf8), using: key).map {
      String(format: "%02x", $0)
    }.joined()
  }
  private func commit(_ next: [Clip]) throws {
    try sql("BEGIN IMMEDIATE")
    do {
      let old = Dictionary(uniqueKeysWithValues: clips.map { ($0.id, $0) })
      let ids = Set(next.map(\.id))
      for clip in clips where !ids.contains(clip.id) {
        let stmt = try prepare("DELETE FROM clips WHERE id=?")
        defer { sqlite3_finalize(stmt) }
        let status = clip.id.withCString { ptr -> Int32 in
          sqlite3_bind_text(stmt, 1, ptr, -1, nil)
          return sqlite3_step(stmt)
        }
        guard status == SQLITE_DONE else { throw ClipError("Could not delete clipboard entry") }
      }
      for clip in next where old[clip.id] != clip {
        let data = try AES.GCM.seal(JSONEncoder().encode(clip), using: key).combined!
        let stmt = try prepare("INSERT OR REPLACE INTO clips(id,payload) VALUES (?,?)")
        defer { sqlite3_finalize(stmt) }
        let status = clip.id.withCString { ptr -> Int32 in
          sqlite3_bind_text(stmt, 1, ptr, -1, nil)
          return data.withUnsafeBytes { bytes in
            sqlite3_bind_blob(stmt, 2, bytes.baseAddress, Int32(data.count), nil)
            return sqlite3_step(stmt)
          }
        }
        guard status == SQLITE_DONE else { throw ClipError("Could not save clipboard entry") }
      }
      try sql("COMMIT")
      clips = next.sorted { $0.copied > $1.copied }
      generation += 1
    } catch {
      try? sql("ROLLBACK")
      throw error
    }
  }
  func expire(now: Date = Date()) throws {
    let next = clips.filter { $0.favorite || now.timeIntervalSince($0.copied) < limits.age }
    if next.count != clips.count { try commit(next) }
    clips.sort { $0.copied > $1.copied }
  }
  func add(_ text: String, source: String, now: Date = Date()) throws {
    guard !text.isEmpty else { return }
    guard text.utf8.count <= limits.itemBytes else {
      throw ClipError("Copy skipped: text exceeds the 1 MiB entry limit")
    }
    let id = identifier(text)
    let favorite = clips.first { $0.id == id }?.favorite ?? false
    var next = clips.filter {
      $0.id != id && ($0.favorite || now.timeIntervalSince($0.copied) < limits.age)
    }
    let incoming = Clip(
      id: id, text: text, source: String(source.prefix(512)), copied: now, favorite: favorite)
    while next.filter({ !$0.favorite }).count + (favorite ? 0 : 1) > limits.ordinary
      || next.reduce(incoming.bytes, { $0 + $1.bytes }) > limits.totalBytes
    {
      guard
        let victim = next.indices.filter({ !next[$0].favorite }).min(by: {
          next[$0].copied < next[$1].copied
        })
      else {
        throw ClipError("Favorites fill clipboard storage. Delete a favorite to save more text.")
      }
      next.remove(at: victim)
    }
    next.append(incoming)
    try commit(next)
  }
  func favorite(_ id: String) throws {
    guard let index = clips.firstIndex(where: { $0.id == id }) else { return }
    var next = clips
    guard next[index].favorite || next.filter(\.favorite).count < limits.favorites else {
      throw ClipError("Favorite limit reached. Remove a favorite first.")
    }
    next[index].favorite.toggle()
    // Unfavoriting an old clip makes it eligible for ordinary retention again.
    next = next.filter { $0.favorite || Date().timeIntervalSince($0.copied) < limits.age }
    while next.filter({ !$0.favorite }).count > limits.ordinary {
      if let index = next.indices.filter({ !next[$0].favorite }).min(by: {
        next[$0].copied < next[$1].copied
      }) {
        next.remove(at: index)
      }
    }
    try commit(next)
  }
  func delete(_ id: String) throws { try commit(clips.filter { $0.id != id }) }
  func clear(includeFavorites: Bool) throws {
    try commit(includeFavorites ? [] : clips.filter(\.favorite))
  }
}
actor ClipWorker {
  private var store: ClipStore?
  /// Damaged rows skipped by the most recent successful open.
  private(set) var skipped = 0
  func open(url: URL, key: SymmetricKey? = nil, interactive: Bool = true) throws -> [Clip] {
    let resolved =
      try key
      ?? ClipKey.load(
        create: !FileManager.default.fileExists(atPath: url.path), interactive: interactive)
    let opened = try ClipStore(url: url, key: resolved)
    store = opened
    skipped = opened.skipped
    return opened.clips
  }
  /// Moves unreadable history aside and starts an empty one. Refused while the Keychain can't answer.
  func reset(url: URL, key: SymmetricKey? = nil) throws -> (clips: [Clip], movedTo: URL?) {
    if key == nil { try ClipKey.requireAccess() }
    store = nil
    let moved = try ClipStore.moveAside(url)
    return (try open(url: url, key: key), moved)
  }
  func run(_ action: (ClipStore) throws -> Void) throws -> (clips: [Clip], changed: Bool) {
    guard let store else {
      throw ClipError(
        "Clipboard history is unavailable. Use Retry or Reset in the Clipboard History menu.")
    }
    let generation = store.generation
    try action(store)
    return (store.clips, store.generation != generation)
  }
}
